#!/usr/bin/env python3
"""
inject.py — apply the LOS patch layer to mortgage-suite-allinone.html

The two engines are not edited. Three things happen:
  1. the Google Fonts link is swapped for the modern stack
  2. patch.css is appended as the last <style> in <head>, so it wins on
     equal specificity without any !important arms race
  3. patch.js is appended as the last <script> before </body>, so every
     function and store it wraps already exists

Re-runnable: an already-patched file is detected and rebuilt from scratch.
"""
import re, sys, pathlib

ROOT  = pathlib.Path(__file__).resolve().parent.parent
SRC   = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "src" / "mortgage-suite-allinone.html")
OUT   = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else ROOT / "dist" / "mortgage-suite-los.html")
HERE  = pathlib.Path(__file__).resolve().parent.parent / "src"

FONT_OLD = re.compile(r'<link href="https://fonts\.googleapis\.com/css2\?[^"]*" rel="stylesheet">')
FONT_NEW = ('<link rel="preconnect" href="https://fonts.googleapis.com">\n'
            '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
            '<link href="https://fonts.googleapis.com/css2?'
            'family=Plus+Jakarta+Sans:wght@400;500;600;700;800&'
            'family=Manrope:wght@400;500;600;700;800&'
            'family=JetBrains+Mono:wght@400;500;600&display=swap" rel="stylesheet">')

BEGIN = "<!-- ===== LOS PATCH LAYER — BEGIN (generated by inject.py) ===== -->"
END   = "<!-- ===== LOS PATCH LAYER — END ===== -->"

def main():
    html = SRC.read_text(encoding="utf-8")

    # Rebuilding: strip any layer already present so this is idempotent.
    if BEGIN in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", html, flags=re.S)

    # 1a. the document's own fonts
    html, n = FONT_OLD.subn(FONT_NEW, html, count=1)
    if n == 0:
        raise SystemExit("Could not find the original Google Fonts link — aborting rather than guessing.")

    # 1b. the report / pay stub windows are separate documents written from a
    #     template string, so they carry their own link and their own faces.
    #     They print, so they get the same stack.
    html = html.replace(
        "family=Inter:wght@400;600;700;800&family=JetBrains+Mono:wght@400;600;700",
        "family=Plus+Jakarta+Sans:wght@400;600;700;800&family=Manrope:wght@400;600;700;800")
    html = html.replace("font-family:'Inter',sans-serif", "font-family:'Plus Jakarta Sans',sans-serif")
    html = html.replace("'Segoe UI',Roboto,Inter,Arial,sans-serif",
                        "'Plus Jakarta Sans','Segoe UI',Roboto,Arial,sans-serif")

    css = (HERE / "patch.css").read_text(encoding="utf-8") \
        + "\n\n" + (HERE / "patch-reno.css").read_text(encoding="utf-8")
    js  = (HERE / "patch.js").read_text(encoding="utf-8")

    # 2. stylesheet, last thing in <head>
    if "</head>" not in html:
        raise SystemExit("No </head> found.")
    head_block = f"\n{BEGIN}\n<style>\n{css}\n</style>\n{END}\n"
    html = html.replace("</head>", head_block + "</head>", 1)

    # 3. script, last thing before </body>
    if "</body>" not in html:
        raise SystemExit("No </body> found.")
    body_block = f"\n{BEGIN}\n<script>\n{js}\n</script>\n{END}\n"
    idx = html.rfind("</body>")
    html = html[:idx] + body_block + html[idx:]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(html, encoding="utf-8")
    print(f"wrote {OUT}  ({len(html):,} bytes, source {len(SRC.read_text(encoding='utf-8')):,})")

if __name__ == "__main__":
    main()
